"""Small, deterministic source map. Standard library only; never imports app code."""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = "docs/REPO_MAP.md"


def scan(root: Path) -> dict:
    paths = [root / "doro.py"]
    for folder in ("doro_app", "extensions"):
        paths.extend(p for p in (root / folder).rglob("*") if p.suffix in {".py", ".js"})
    files = {}
    for path in sorted(set(paths)):
        if not path.is_file() or path.is_symlink() or "res" in path.relative_to(root).parts:
            continue
        rel = path.relative_to(root).as_posix()
        text = path.read_text(encoding="utf-8-sig")
        symbols, imports = [], set()
        if path.suffix == ".py":
            tree = ast.parse(text, filename=rel)

            def definitions(nodes, prefix=""):
                for node in nodes:
                    if isinstance(node, ast.ClassDef):
                        signature = f"class {prefix}{node.name}"
                        symbols.append((prefix + node.name, node.lineno, signature))
                        definitions(node.body, prefix + node.name + ".")
                    elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        signature = f"{prefix}{node.name}({ast.unparse(node.args)})"
                        if node.returns:
                            signature += " -> " + ast.unparse(node.returns)
                        symbols.append((prefix + node.name, node.lineno, signature))

            definitions(tree.body)
            package = rel[:-3].split("/")[:-1]
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    imports.update(alias.name for alias in node.names)
                elif isinstance(node, ast.ImportFrom):
                    base = package[:len(package) - node.level + 1] if node.level else []
                    if node.module:
                        base += node.module.split(".")
                    imports.add(".".join(base))
                    imports.update(".".join(base + [alias.name]) for alias in node.names)
        else:
            for match in re.finditer(r"^[ \t]*(?:async\s+)?function\s+(\w+)\s*(\([^\n]*?\))", text, re.M):
                line = text[:match.start()].count("\n") + 1
                symbols.append((match[1], line, "function " + match[1] + match[2]))
        files[rel] = {"symbols": symbols, "imports": imports}
    modules = {p[:-3].replace("/", ".").removesuffix(".__init__"): p
               for p in files if p.endswith(".py")}
    for data in files.values():
        data["imports"] = sorted({modules[name] for name in data["imports"] if name in modules})
    return files


def load_areas(root: Path, files: dict) -> list[dict]:
    areas = json.loads((root / "docs/ai/areas.json").read_text(encoding="utf-8-sig"))
    covered = set()
    for area in areas:
        members = {p.relative_to(root).as_posix() for pattern in area["scope"]
                   for p in root.glob(pattern)} & files.keys()
        area["members"] = sorted(members)
        covered.update(members)
        for entry in area["entries"]:
            if entry not in members:
                raise ValueError(f"{area['id']}: entry missing or outside scope: {entry}")
        for test in area["tests"]:
            if not (root / test).exists():
                raise ValueError(f"{area['id']}: missing test path: {test}")
    if files.keys() - covered:
        raise ValueError("Unmapped source files; update areas.json: " + ", ".join(sorted(files.keys() - covered)))
    return areas


def summary(files: dict, areas: list[dict]) -> str:
    # Track paths/public interfaces, not timestamps, line shifts or function bodies.
    surface = [(p, [s[2] for s in d["symbols"] if not s[0].split(".")[-1].startswith("_")])
               for p, d in files.items()]
    digest = hashlib.sha256(json.dumps(surface, ensure_ascii=False).encode()).hexdigest()[:16]
    lines = ["# Doro repo 地圖", "", "<!-- Generated by python scripts/repo_map.py --write; do not hand edit. -->",
             "", "先定位功能，再讀入口與相關測試。以下不是完整程式碼，也不是要求全部閱讀的清單。",
             f"來源：{len(files)} 個 Python／JavaScript 檔案；公開介面指紋 `{digest}`。", "",
             "`python scripts/repo_map.py --focus 分頁` 可查目前符號、行號及內部 import。", "",
             "| 功能 / focus | 職責 | 先讀入口 | 測試 |", "| --- | --- | --- | --- |"]
    for area in areas:
        entries = "<br>".join(f"[{p.rsplit('/', 1)[-1]}](../{p})" for p in area["entries"])
        tests = "<br>".join(f"[{p}](../{p})" for p in area["tests"])
        lines.append(f"| {area['name']} / `{area['id']}` | {area['purpose']} | {entries} | {tests} |")
    lines += ["", "## 跨模組路徑", "",
              "- 啟動：`doro.py → cli.py → app.py`；`bootstrap.py` 組裝設定與 repository／service。",
              "- 聊天與網頁：`ChatOrchestrator → ChatController / WebRuntime → present_character_reply`。",
              "- 分頁：`content.js → background.js → PresenceBridge → PresenceController → ChatOrchestrator`。",
              "- 角色動作：`ActionDispatcher → phases → MovementManager / StateService`。",
              "- 基本活潑：`IdleBehaviorManager`；情境活潑：`PresenceController`，兩者不能互相取代。",
              "", "## 深入時再讀", "",
              "[語彙](../CONTEXT.md) · [架構決策](adr/) · [功能細節](ai/FEATURE_GUIDE.md) · "
              "[索引工具與維護](ai/WORKFLOW.md) · [文件索引](INDEX.md)", ""]
    return "\n".join(lines)


def bounded(text: str, max_chars: int) -> str:
    if len(text) <= max_chars:
        return text
    notice = "\n[已省略其餘內容；縮小 --focus 或提高 --max-chars。此限制是字元數，不是 token。]\n"
    return text[:max_chars - len(notice)].rsplit("\n", 1)[0] + notice


def focused(files: dict, areas: list[dict], query: str, max_chars: int) -> str:
    q = query.strip().replace("\\", "/").casefold()
    if not q:
        raise ValueError("--focus must not be empty")
    scores = {}
    direct = set()
    for path, data in files.items():
        names = [s[0].casefold() for s in data["symbols"]]
        if q == path.casefold():
            scores[path] = 100
        elif any(q == n or q == n.split(".")[-1] for n in names):
            scores[path] = 90
        elif q in path.casefold() or any(q in n for n in names):
            scores[path] = 60
        if path in scores:
            direct.add(path)
    selected = [a for a in areas if q in [a["id"], a["name"], *a["aliases"]]
                or direct.intersection(a["members"])]
    for area in selected:
        for path in area["members"]:
            scores[path] = max(scores.get(path, 0), 30 if path in area["entries"] else 10)
    if not scores:
        raise ValueError(f"No match for {query!r}; use an area id, alias, path or symbol from docs/REPO_MAP.md")
    # One hop in either direction surfaces callers/dependencies without flooding
    # the output with every transitive dependency. This is not a call graph.
    seeds = direct or {p for p, score in scores.items() if score >= 30}
    for path, data in files.items():
        if path in seeds:
            for dep in data["imports"]:
                scores.setdefault(dep, 5)
        elif seeds.intersection(data["imports"]):
            scores.setdefault(path, 5)
    lines = [f"# Focus: {query}", "", "只列宣告與靜態 import；讀實作前用 rg 確認呼叫位置。", ""]
    for area in selected:
        lines += [f"{area['name']}：{area['purpose']}", "測試：" + ", ".join(area["tests"])]
    for path in sorted(scores, key=lambda p: (-scores[p], p)):
        data = files[path]
        lines += ["", f"## {path}"]
        if data["imports"]:
            imports = sorted(data["imports"], key=lambda p: (p not in seeds, p))
            extra = f"（另有 {len(imports) - 8} 個）" if len(imports) > 8 else ""
            lines.append("內部 import：" + ", ".join(imports[:8]) + extra)
        symbols = sorted(data["symbols"], key=lambda s: (q not in s[0].casefold(), s[0].split(".")[-1].startswith("_"), s[1]))
        for name, line, signature in symbols[:10]:
            lines.append(f"- L{line}: `{signature[:220]}`")
        if len(symbols) > 10:
            lines.append(f"- 另有 {len(symbols) - 10} 個宣告；用 --focus 符號 縮小範圍。")
        if not symbols:
            lines.append("- 無可抽取宣告；直接查看此入口（JS 僅抽取 function 宣告）。")
    return bounded("\n".join(lines) + "\n", max_chars)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--focus", help="Area id, Chinese alias, source path or symbol")
    mode.add_argument("--write", action="store_true", help="Regenerate docs/REPO_MAP.md")
    mode.add_argument("--check", action="store_true", help="Fail if the committed map is stale")
    parser.add_argument("--max-chars", type=int, default=12000, help="Output character budget (not tokens), >=512")
    args = parser.parse_args(argv)
    if args.max_chars < 512:
        parser.error("--max-chars must be >=512")
    try:
        files = scan(ROOT)
        areas = load_areas(ROOT, files)
        expected = summary(files, areas)
        output = ROOT / OUTPUT
        if args.write:
            output.write_text(expected, encoding="utf-8", newline="\n")
            print(f"Updated {OUTPUT}")
        elif args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != expected:
                raise ValueError("Repo map is stale. Run: python scripts/repo_map.py --write")
            print("Repo map is current; all source areas and test paths resolve.")
        else:
            print(focused(files, areas, args.focus, args.max_chars) if args.focus else bounded(expected, args.max_chars), end="")
        return 0
    except (OSError, ValueError, SyntaxError) as exc:
        print(str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
